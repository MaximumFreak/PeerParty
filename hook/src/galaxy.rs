/// A stand-in: its vtable, then the real object, where the forwarding stubs read it.
#[repr(C)]
struct Proxy {
    vtable: *const usize,
    real: usize,
}

static PROXIES: LazyLock<Mutex<HashMap<usize, usize>>> = LazyLock::new(Mutex::default);
static REALS: LazyLock<Mutex<HashMap<usize, (usize, Iface)>>> = LazyLock::new(Mutex::default);

fn overrides(iface: Iface) -> Vec<(&'static str, usize)> {
    match iface {
        Iface::Registrar => registrar(),
        Iface::User => [user(), ext::user()].concat(),
        Iface::Friends => [friends(), ext::friends()].concat(),
        Iface::Matchmaking => matchmaking(),
        Iface::Networking => networking(),
        Iface::Stats => ext::stats(),
        Iface::Utils => ext::utils(),
        Iface::Apps => ext::apps(),
        Iface::Storage => ext::storage(),
        Iface::CloudStorage => ext::cloud_storage(),
        Iface::Telemetry => ext::telemetry(),
        Iface::Chat => ext::chat(),
        Iface::CustomNetworking => ext::custom_networking(),
    }
}

fn wrap(real: usize, iface: Iface) -> usize {
    if real == 0 || !net::enabled() {
        return real;
    }
    if REALS.lock().unwrap().contains_key(&real) {
        return real;
    }
    if let Some(p) = PROXIES.lock().unwrap().get(&real) {
        return *p;
    }
    let Some((names, certain)) = layout(iface) else { return real };
    let mine = overrides(iface);
    let mut ours = 0;
    let mut vtable = Vec::with_capacity(names.len());
    for (i, n) in names.iter().enumerate() {
        let found = mine.iter().find(|(m, _)| m == n).map(|(_, f)| *f).or_else(|| old_shape(iface, n));
        let f = match found {
            Some(f) if i < certain => {
                ours += 1;
                f
            }
            _ => match crate::steamobj::forward_stub(i) {
                Some(s) => s,
                None => return real,
            },
        };
        vtable.push(f);
    }
    let vtable = Box::leak(vtable.into_boxed_slice()).as_ptr();
    let proxy = Box::leak(Box::new(Proxy { vtable, real })) as *const Proxy as usize;
    PROXIES.lock().unwrap().insert(real, proxy);
    REALS.lock().unwrap().insert(proxy, (real, iface));
    log!("galaxy {}: peerparty answers {ours} of its {} methods", iface.class(), names.len() - 1);
    proxy
}

/// The real object and method `name` behind a stand-in.
fn real_method(this: usize, name: &str) -> Option<(usize, usize)> {
    let (real, iface) = *REALS.lock().unwrap().get(&this)?;
    let i = slot_of(iface, name)?;
    let vt = unsafe { *(real as *const *const usize) };
    Some((real, unsafe { *vt.add(i) }))
}

/// Calls the real object's method `name` for a stand-in `this`.
macro_rules! real {
    ($this:expr, $name:literal, fn($($t:ty),*) -> $r:ty, $default:expr $(, $arg:expr)* $(,)?) => {{
        match real_method($this, $name) {
            Some((real, f)) => {
                #[cfg(target_arch = "x86")]
                let f: unsafe extern "thiscall" fn(usize $(, $t)*) -> $r = unsafe { std::mem::transmute(f) };
                #[cfg(not(target_arch = "x86"))]
                let f: unsafe extern "C" fn(usize $(, $t)*) -> $r = unsafe { std::mem::transmute(f) };
                unsafe { f(real $(, $arg)*) }
            }
            None => $default,
        }
    }};
}

/// Calls virtual method `slot` of a game object (thiscall on x86).
macro_rules! virt {
    ($obj:expr, $slot:expr, fn($($t:ty),*) $(, $arg:expr)*) => {{
        let obj: usize = $obj;
        unsafe {
            let f = *(*(obj as *const *const usize)).add($slot);
            #[cfg(target_arch = "x86")]
            let f: unsafe extern "thiscall" fn(usize $(, $t)*) = std::mem::transmute(f);
            #[cfg(not(target_arch = "x86"))]
            let f: unsafe extern "C" fn(usize $(, $t)*) = std::mem::transmute(f);
            f(obj $(, $arg)*)
        }
    }};
}

