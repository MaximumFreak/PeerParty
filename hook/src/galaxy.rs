vmethod! {
    fn send_lobby_message(_this: usize, lobby: Gid, data: *const u8, size: u32) -> bool {
        ours();
        let id = gid(lobby);
        let (Some(lan), Some(l)) = (lan(), view(id)) else { return false };
        if l.member(lan.me()).is_none() {
            return false;
        }
        let body = if data.is_null() || size == 0 { Vec::new() } else { unsafe { std::slice::from_raw_parts(data, size as usize) }.to_vec() };
        let mut packet = id.to_le_bytes().to_vec();
        packet.extend_from_slice(&body);
        for m in l.members.iter().filter(|m| m.id != lan.me()) {
            lan.send(m.id, CHAT, 0, &packet, true, true, true);
        }
        // The sender hears its own message too.
        received_message(id, my_id(), body);
        true
    }
}

fn received_message(lobby: u64, sender: u64, body: Vec<u8>) {
    // A message's id is its place in the lobby's list, kept until we leave.
    let (msg, len) = {
        let mut st = S.lock().unwrap();
        let list = st.messages.entry(lobby).or_default();
        let len = body.len() as u32;
        list.push((sender, body));
        (list.len() as u32 - 1, len)
    };
    let to = targets(LOBBY_MESSAGE, 0);
    later(move || {
        for l in to {
            virt!(l, 1, fn(*const u64, *const u64, u32, u32), &lobby, &sender, msg, len);
        }
    });
}

vmethod! {
    fn get_lobby_message(_this: usize, lobby: Gid, msg: u32, sender: *mut u64, buf: *mut c_char, len: u32) -> u32 {
        ours();
        let st = S.lock().unwrap();
        let Some((from, body)) = st.messages.get(&gid(lobby)).and_then(|m| m.get(msg as usize)) else { return 0 };
        if !sender.is_null() {
            unsafe { *sender = *from };
        }
        let n = body.len().min(len as usize);
        if !buf.is_null() && n > 0 {
            unsafe { std::ptr::copy_nonoverlapping(body.as_ptr(), buf as *mut u8, n) };
        }
        n as u32
    }
}

