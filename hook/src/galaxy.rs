fn gid(g: Gid) -> u64 {
    #[cfg(not(target_arch = "x86"))]
    {
        if g.is_null() { 0 } else { unsafe { std::ptr::read_unaligned(g) } }
    }
    #[cfg(target_arch = "x86")]
    {
        g
    }
}

/// A GalaxyID to pass by value to the game.
