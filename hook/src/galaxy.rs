/// Moves packets that have arrived into our per-channel queues; returns the new ones.
fn take_packets() -> Vec<(u8, u32)> {
    let Some(lan) = lan() else { return Vec::new() };
    let mut fresh = Vec::new();
    while let Some(p) = lan.receive_where(None, |s| s == P2P) {
        let from = galaxy_id(p.peer);
        fresh.push((p.channel, p.data.len() as u32));
        S.lock().unwrap().packets.entry(p.channel).or_default().push_back((from, p.data));
    }
    fresh
}

vmethod! {
    fn send_p2p(_this: usize, to: Gid, data: *const u8, size: u32, kind: u32, channel: u8) -> bool {
        ours();
        let id = gid(to);
        let (Some(lan), Some(peer)) = (lan(), peer_of(id)) else {
            crate::log::throttled(&format!("galaxy p2p to unknown {id}"), 2, |_| log!("galaxy SendP2PPacket to {id}, who isn't on the LAN"));
            return false;
        };
        let body = if data.is_null() || size == 0 { &[][..] } else { unsafe { std::slice::from_raw_parts(data, size as usize) } };
        // P2P_SEND_UNRELIABLE 0, RELIABLE 1, UNRELIABLE_IMMEDIATE 2, RELIABLE_IMMEDIATE 3.
        let reliable = kind == 1 || kind == 3;
        let r = lan.send(peer, P2P, channel, body, reliable, true, true);
        crate::log::throttled("galaxy SendP2PPacket", 4, |n| log!("galaxy SendP2PPacket n={n} to {id} {size} bytes ch={channel} -> {r:?}"));
        !matches!(r, peerparty_core::SendResult::Dropped | peerparty_core::SendResult::NoChannel)
    }
}

fn front(channel: u8, take: bool) -> Option<(u64, Vec<u8>)> {
    take_packets();
    let mut st = S.lock().unwrap();
    let q = st.packets.get_mut(&channel)?;
    if take { q.pop_front() } else { q.front().cloned() }
}

fn hand_out(p: Option<(u64, Vec<u8>)>, dest: *mut u8, cap: u32, size: *mut u32, from: *mut u64) -> bool {
    let Some((who, data)) = p else { return false };
    let n = data.len().min(cap as usize);
    unsafe {
        if !dest.is_null() && n > 0 {
            std::ptr::copy_nonoverlapping(data.as_ptr(), dest, n);
        }
        if !size.is_null() {
            *size = n as u32;
        }
        if !from.is_null() {
            *from = who;
        }
    }
    true
}

vmethod! {
    fn peek_p2p(_this: usize, dest: *mut u8, cap: u32, size: *mut u32, from: *mut u64, channel: u8) -> bool {
        ours();
        hand_out(front(channel, false), dest, cap, size, from)
    }
}

vmethod! {
    fn read_p2p(_this: usize, dest: *mut u8, cap: u32, size: *mut u32, from: *mut u64, channel: u8) -> bool {
        ours();
        hand_out(front(channel, true), dest, cap, size, from)
    }
}

vmethod! {
    fn p2p_available(_this: usize, size: *mut u32, channel: u8) -> bool {
        ours();
        let Some((_, data)) = front(channel, false) else { return false };
        if !size.is_null() {
            unsafe { *size = data.len() as u32 };
        }
        true
    }
}

vmethod! { fn pop_p2p(_this: usize, channel: u8) { ours(); let _ = front(channel, true); } }
vmethod! { fn ping_with(_this: usize, _to: Gid) -> i32 { ours(); 1 } }

