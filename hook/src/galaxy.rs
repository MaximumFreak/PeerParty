        let base = unsafe { LoadLibraryExW(wide.as_ptr(), std::ptr::null_mut(), DONT_RESOLVE) } as usize;
        assert_ne!(base, 0);
        assert_eq!(rtti_slots(base, "IMatchmaking"), Some(34));
        assert_eq!(rtti_slots(base, "IFriends"), Some(41));
        assert_eq!(rtti_slots(base, "IUser"), Some(38));
