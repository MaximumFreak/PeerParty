/// A user data's owner: GalaxyID() (0) is this player.
fn user_data_of(user: Gid) -> Vec<(String, String)> {
    let id = gid(user);
    if id != 0 && id != my_id() {
        return Vec::new();
    }
    S.lock().unwrap().user_data.iter().map(|(k, v)| (k.clone(), v.clone())).collect()
}

/// User data changed or arrived: the call's listener and the global specific ones, and
/// for this player's own also the global user data listeners.
fn user_data_updated(id: u64, listener: usize) {
    let id = if id == 0 { my_id() } else { id };
    let specific = targets(SPECIFIC_USER_DATA, listener);
    let own = if id == my_id() { targets(USER_DATA, 0) } else { Vec::new() };
    later(move || {
        for l in specific {
            virt!(l, 1, fn(Gid), by_value(&id));
        }
        for l in own {
            virt!(l, 1, fn());
        }
    });
}

vmethod! {
    fn request_user_data(_this: usize, user: Gid, listener: usize) {
        ours();
        user_data_updated(gid(user), listener);
    }
}

