/// Galaxy's LobbyComparisonType: how the lobby's value compares with the filter's.
fn compare(ord: std::cmp::Ordering, cmp: u32) -> bool {
    use std::cmp::Ordering::*;
    match cmp {
        0 => ord == Equal,
        1 => ord != Equal,
        2 => ord == Greater,
        3 => ord != Less,
        4 => ord == Less,
        5 => ord != Greater,
        _ => true,
    }
}

fn passes(l: &Lobby, f: &Filter) -> bool {
    match f {
        Filter::Str(k, v, cmp) => match text(l, k) {
            Some(have) => compare(have.as_str().cmp(v.as_str()), *cmp),
            None => *cmp == 1,
        },
        Filter::Num(k, v, cmp) => match text(l, k).and_then(|t| t.trim().parse::<i64>().ok()) {
            Some(have) => compare(have.cmp(v), *cmp),
            None => *cmp == 1,
        },
        Filter::Near(..) => true,
    }
}

