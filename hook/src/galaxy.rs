fn lan_id(peer: PeerId) -> u64 {
    let v = u64::from_le_bytes(peer.0[..8].try_into().unwrap()) & 0x007F_FFFF_FFFF_FFFF;
    (2u64 << 56) | (1u64 << 55) | v
}

/// A LAN player's GalaxyID: the one it told us, else its LAN one. Ours for ourselves.
fn galaxy_id(peer: PeerId) -> u64 {
    if lan().is_some_and(|l| l.me() == peer) {
        return my_id();
    }
    let told = lan()
        .map(|l| l.presence(peer))
        .unwrap_or_default()
        .iter()
        .find(|(k, _)| k == KEY_ID)
        .and_then(|(_, v)| v.parse::<u64>().ok());
    let id = told.unwrap_or_else(|| lan_id(peer));
    S.lock().unwrap().ids.insert(id, peer);
    id
}

fn peer_of(id: u64) -> Option<PeerId> {
    let lan = lan()?;
    if id != 0 && id == my_id() {
        return Some(lan.me());
    }
    if let Some(p) = S.lock().unwrap().ids.get(&id).copied() {
        return Some(p);
    }
    lan.peers().into_iter().map(|(p, _)| p).find(|p| galaxy_id(*p) == id)
}

fn my_id() -> u64 {
    let known = ME.load(Ordering::Relaxed);
    if known != 0 {
        return known;
    }
    let Some(lan) = lan() else { return 0 };
    let id = lan_id(lan.me());
    ME.store(id, Ordering::Relaxed);
    publish();
    id
}

fn my_name() -> String {
    lan().map(|l| l.name().to_string()).unwrap_or_else(|| "Player".into())
}

fn friends_list() -> Vec<(PeerId, String)> {
    let mut v = lan().map(|l| l.peers()).unwrap_or_default();
    v.sort_by_key(|(id, _)| *id);
    v
}

fn publish() {
    let mut kv: Vec<(String, String)> = S.lock().unwrap().rich.iter().map(|(k, v)| (format!("{KEY_RP}{k}"), v.clone())).collect();
    let me = ME.load(Ordering::Relaxed);
    if me != 0 {
        kv.push((KEY_ID.into(), me.to_string()));
    }
    net::set_presence("galaxy", kv);
}

fn presence_of(id: u64) -> Vec<(String, String)> {
    if id == 0 || id == my_id() {
        return S.lock().unwrap().rich.iter().map(|(k, v)| (k.clone(), v.clone())).collect();
    }
    let (Some(lan), Some(p)) = (lan(), peer_of(id)) else { return Vec::new() };
    lan.presence(p)
        .into_iter()
        .filter_map(|(k, v)| k.strip_prefix(KEY_RP).map(|k| (k.to_string(), v)))
        .collect()
}

/// Our rich presence "connect": where a friend joining us should go.
