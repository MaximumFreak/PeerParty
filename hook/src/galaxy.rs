type AccessorFn = unsafe extern "C" fn() -> usize;
type VoidFn = unsafe extern "C" fn();
type ErrorFn = unsafe extern "C" fn() -> usize;

static ACCESSORS: OnceLock<Vec<(Iface, GenericDetour<AccessorFn>)>> = OnceLock::new();
static PROCESS: OnceLock<GenericDetour<VoidFn>> = OnceLock::new();
static GET_ERROR: OnceLock<GenericDetour<ErrorFn>> = OnceLock::new();

fn accessor(iface: Iface) -> usize {
    let Some((_, h)) = ACCESSORS.get().and_then(|v| v.iter().find(|(i, _)| *i == iface)) else { return 0 };
    let real = unsafe { h.call() };
    wrap(real, iface)
}

