unsafe extern "C" fn detour_process() {
    if let Some(h) = PROCESS.get() {
        unsafe { h.call() };
    }
    let _ = std::panic::catch_unwind(pump);
}

unsafe extern "C" fn detour_get_error() -> usize {
    if OURS_LAST.with(|c| c.replace(false)) {
        return 0;
    }
    let err = GET_ERROR.get().map_or(0, |h| unsafe { h.call() });
    if err != 0 && SIGNED_IN.load(Ordering::Relaxed) {
        // A call PeerParty left to Galaxy failed: IError's GetMsg (slot 2)
        // names it ("RequestUserData: not logged on").
        let msg = unsafe {
            let f = *(*(err as *const *const usize)).add(2);
            #[cfg(target_arch = "x86")]
            let f: unsafe extern "thiscall" fn(usize) -> *const c_char = std::mem::transmute(f);
            #[cfg(not(target_arch = "x86"))]
            let f: unsafe extern "C" fn(usize) -> *const c_char = std::mem::transmute(f);
            s(f(err))
        };
        crate::log::gap("galaxy", &format!("{msg} (left to Galaxy, which failed)"));
    }
    err
}

/// Hooks Galaxy's accessors, ProcessData and GetError. Returns the addresses patched.
pub fn attach(base: usize, name: &str, exports: &[Export]) -> Vec<usize> {
    MODULE.store(base, Ordering::Relaxed);
    let find = |prefix: &str| exports.iter().find(|e| e.name.starts_with(prefix)).map(|e| e.addr as usize);
    let mut patched = Vec::new();
    let mut accessors = Vec::new();
    for (prefix, iface, f) in [
        ("?ListenerRegistrar@api@galaxy@@", Iface::Registrar, detour_registrar as AccessorFn),
        ("?User@api@galaxy@@", Iface::User, detour_user as AccessorFn),
        ("?Friends@api@galaxy@@", Iface::Friends, detour_friends as AccessorFn),
        ("?Matchmaking@api@galaxy@@", Iface::Matchmaking, detour_matchmaking as AccessorFn),
        ("?Networking@api@galaxy@@", Iface::Networking, detour_networking as AccessorFn),
        ("?Stats@api@galaxy@@", Iface::Stats, detour_stats as AccessorFn),
        ("?Utils@api@galaxy@@", Iface::Utils, detour_utils as AccessorFn),
        ("?Apps@api@galaxy@@", Iface::Apps, detour_apps as AccessorFn),
        ("?Storage@api@galaxy@@", Iface::Storage, detour_storage as AccessorFn),
        ("?CloudStorage@api@galaxy@@", Iface::CloudStorage, detour_cloud_storage as AccessorFn),
        ("?Telemetry@api@galaxy@@", Iface::Telemetry, detour_telemetry as AccessorFn),
        ("?Chat@api@galaxy@@", Iface::Chat, detour_chat as AccessorFn),
        ("?CustomNetworking@api@galaxy@@", Iface::CustomNetworking, detour_custom_networking as AccessorFn),
    ] {
        let Some(a) = find(prefix) else { continue };
        let target: AccessorFn = unsafe { std::mem::transmute(a) };
        let h = with_lock(|| unsafe {
            let h = GenericDetour::new(target, f).ok()?;
            h.enable().ok()?;
            Some(h)
        });
        match h {
            Some(h) => {
                accessors.push((iface, h));
                patched.push(a);
            }
            None => log!("galaxy {prefix}: not hooked"),
        }
    }
    let _ = ACCESSORS.set(accessors);
    if let Some(a) = find("?ProcessData@api@galaxy@@") {
        if arm(&PROCESS, a, detour_process as VoidFn) {
            patched.push(a);
        }
    }
    if let Some(a) = find("?GetError@api@galaxy@@") {
        if arm(&GET_ERROR, a, detour_get_error as ErrorFn) {
            patched.push(a);
        }
    }
    net::subscribe(Front::Galaxy);
    log!("galaxy on for {name}: LAN players are friends, lobbies and P2P go over the LAN ({} exports hooked)", patched.len());
    patched
}

fn arm<T>(slot: &OnceLock<GenericDetour<T>>, addr: usize, detour: T) -> bool
where
    T: retour::Function + Copy + Send + Sync + 'static,
{
    with_lock(|| {
        let target: T = unsafe { std::mem::transmute_copy(&addr) };
        let Ok(h) = (unsafe { GenericDetour::new(target, detour) }) else { return false };
        if slot.set(h).is_err() {
            return false;
        }
        unsafe { slot.get().unwrap().enable() }.is_ok()
    })
}

