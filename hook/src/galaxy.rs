/// A C string that stays valid.
fn c_str(text: &str) -> *const c_char {
    let mut m = STRINGS.lock().unwrap();
    m.entry(text.to_string())
        .or_insert_with(|| CString::new(text.replace('\0', "")).unwrap_or_default())
        .as_ptr()
}

fn copy_out(text: &str, buf: *mut c_char, len: u32) {
    if buf.is_null() || len == 0 {
        return;
    }
    let n = text.len().min(len as usize - 1);
    unsafe {
        std::ptr::copy_nonoverlapping(text.as_ptr(), buf as *mut u8, n);
        *buf.add(n) = 0;
    }
}

