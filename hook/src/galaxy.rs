//! GOG Galaxy (`Galaxy64.dll` / `Galaxy.dll`) on the LAN.
//!
//! Galaxy is C++: the game gets interface objects from `galaxy::api::User()`,
//! `Friends()`, `Matchmaking()`, `Networking()` and `ListenerRegistrar()`, and results
//! come back to listener objects during `ProcessData()`. In a game started through PeerParty those accessors
//! hand out stand-ins like steamobj.rs's: PeerParty's methods for signing in, friends
//! and rich presence, lobbies and P2P packets, and for every other slot a stub that
//! jumps to the real method with the real object. Listeners the game registers
//! globally are noted on the way through to the real registrar; PeerParty's results go
//! to the listener passed with the call and to the global ones of that type, from the
//! game's own `ProcessData()`.
//!
//! - Signing in succeeds at once with a LAN GalaxyID; the game is "logged on".
//! - User data (`RequestUserData`, `SetUserData`, ...) is answered: this player's lives for
//!   the run, anyone else's is empty. Galaxy throws "not logged on" without GOG.
//! - LAN players are friends, with names, rich presence ("PeerParty:gog:" keys in LAN
//!   presence) and invites: `SendInvitation` and the overlay invite dialog become LAN
//!   invites, which arrive as `OnGameJoinRequested` with the connection string.
//! - Lobbies are LAN lobbies (namespace "galaxy.lobby"): data, member data, messages,
//!   owner changes, search with Galaxy's comparisons.
//! - P2P packets travel on LAN channels (socket "galaxy:p2p", Galaxy's channel number
//!   as the channel); there is no session to accept.
//!
//! Layouts come from the SDK headers of every Galaxy version (galaxyvt.rs, generated by
//! tools/galaxy_vtables.py), picked by the DLL's file version: MSVC's vtable order, the
//! virtual destructor first. Before wrapping an interface its slot count is checked
//! against the abstract class's own vtable in the loaded DLL (found through MSVC RTTI);
//! an interface whose count doesn't match is left alone. ListenerType values come from
//! the same version's enum. Older SDKs had no per-call listeners and overloaded
//! `SignIn`; those shapes are answered too, their results going to global listeners.
//!
//! ABI: `GalaxyID` has a user-written copy constructor, so MSVC passes one by value as
//! a pointer to a copy on x64 (on x86 the 8 bytes go on the stack) and returns one
//! through a hidden pointer after `this`.

