/// The layout this DLL has for an interface, and how many of its slots are certain.
struct Layout {
    names: &'static [&'static str],
    certain: usize,
}

static LAYOUTS: LazyLock<Mutex<HashMap<Iface, Option<Layout>>>> = LazyLock::new(Mutex::default);
static MODULE: AtomicUsize = AtomicUsize::new(0);
/// The SDK's row in galaxyvt::VERSIONS, once known.
static ROW: OnceLock<Option<usize>> = OnceLock::new();

fn image(base: usize) -> &'static [u8] {
    unsafe {
        let nt = base + *((base + 0x3c) as *const u32) as usize;
        let size = *((nt + 0x18 + 0x38) as *const u32) as usize;
        std::slice::from_raw_parts(base as *const u8, size)
    }
}

/// (rva, size, characteristics) of each section.
fn sections(base: usize) -> Vec<(usize, usize, u32)> {
    unsafe {
        let nt = base + *((base + 0x3c) as *const u32) as usize;
        let count = *((nt + 6) as *const u16) as usize;
        let opt = *((nt + 20) as *const u16) as usize;
        let first = nt + 24 + opt;
        (0..count)
            .map(|i| {
                let s = first + i * 40;
                let size = *((s + 8) as *const u32) as usize;
                let rva = *((s + 12) as *const u32) as usize;
                let ch = *((s + 36) as *const u32);
                (rva, size, ch)
            })
            .collect()
    }
}

fn find_all(hay: &[u8], needle: &[u8]) -> Vec<usize> {
    hay.windows(needle.len()).enumerate().filter(|(_, w)| *w == needle).map(|(i, _)| i).collect()
}

/// The DLL's file version (1.152.6 for Galaxy 1.152.6.0), from its VS_FIXEDFILEINFO.
fn file_version(base: usize) -> Option<(u32, u32, u32)> {
    let img = image(base);
    let at = find_all(img, &0xFEEF_04BDu32.to_le_bytes()).into_iter().next()?;
    let ms = u32::from_le_bytes(img.get(at + 8..at + 12)?.try_into().ok()?);
    let ls = u32::from_le_bytes(img.get(at + 12..at + 16)?.try_into().ok()?);
    Some((ms >> 16, ms & 0xffff, ls >> 16))
}

/// The newest SDK in galaxyvt::VERSIONS that isn't newer than the DLL.
fn row_for(version: (u32, u32, u32)) -> Option<usize> {
    galaxyvt::VERSIONS.iter().rposition(|(v, ..)| *v <= version)
}

fn row() -> Option<usize> {
    *ROW.get_or_init(|| {
        let base = MODULE.load(Ordering::Relaxed);
        let version = file_version(base)?;
        let row = row_for(version);
        let (a, b, c) = version;
        match row {
            Some(r) => {
                let (x, y, z) = galaxyvt::VERSIONS[r].0;
                log!("galaxy SDK {a}.{b}.{c}: layouts of SDK {x}.{y}.{z}");
            }
            None => log!("galaxy SDK {a}.{b}.{c} is older than any layout peerparty has: left alone"),
        }
        row
    })
}

/// The SDK version PeerParty is using layouts for.
fn sdk() -> (u32, u32, u32) {
    row().map_or((0, 0, 0), |r| galaxyvt::VERSIONS[r].0)
}

/// A ListenerType's value in this SDK.
fn listener_type(name: &str) -> Option<u32> {
    let enums = galaxyvt::LISTENER_TYPES[galaxyvt::VERSIONS[row()?].2 as usize];
    enums.iter().position(|n| *n == name).map(|i| i as u32)
}

/// The slot count of `galaxy::api::<class>`'s own vtable in the DLL at `base`, through
/// MSVC RTTI: type descriptor ".?AV<class>@api@galaxy@@", its complete object locator,
/// the vtable that points at it.
fn rtti_slots(base: usize, class: &str) -> Option<usize> {
    let img = image(base);
    let ptr = size_of::<usize>();
    let name = format!(".?AV{class}@api@galaxy@@\0");
    let at = find_all(img, name.as_bytes()).into_iter().next()?;
    let td = at - 2 * ptr;
    let secs = sections(base);
    let data: Vec<(usize, usize)> = secs.iter().filter(|s| s.2 & 0x4000_0000 != 0 && s.2 & 0x2000_0000 == 0).map(|s| (s.0, s.1)).collect();
    let code: Vec<(usize, usize)> = secs.iter().filter(|s| s.2 & 0x2000_0000 != 0).map(|s| (s.0, s.1)).collect();
    let rd32 = |o: usize| u32::from_le_bytes(img[o..o + 4].try_into().unwrap()) as usize;
    let rdp = |o: usize| if ptr == 8 { u64::from_le_bytes(img[o..o + 8].try_into().unwrap()) as usize } else { rd32(o) };
    let is_code = |va: usize| va >= base && code.iter().any(|(r, s)| (base + r..base + r + s).contains(&va));
    // The locator: x64 has signature 1 and image-relative fields, x86 signature 0 and
    // addresses.
    let mut col = None;
    'find: for (r, s) in &data {
        let mut o = *r;
        while o + 24 <= r + s && o + 24 <= img.len() {
            let sig = rd32(o);
            let offset = rd32(o + 4);
            let td_field = rd32(o + 12);
            let hit = if ptr == 8 {
                sig == 1 && offset == 0 && td_field == td && rd32(o + 20) == o
            } else {
                sig == 0 && offset == 0 && td_field == base + td
            };
            if hit {
                col = Some(o);
                break 'find;
            }
            o += 4;
        }
    }
    let col_va = base + col?;
    for (r, s) in &data {
        let mut o = *r;
        while o + ptr <= r + s && o + 2 * ptr <= img.len() {
            if rdp(o) == col_va {
                let mut n = 0;
                while o + ptr * (n + 2) <= img.len() && is_code(rdp(o + ptr * (n + 1))) {
                    n += 1;
                }
                return Some(n);
            }
            o += ptr;
        }
    }
    None
}

fn layout(iface: Iface) -> Option<(&'static [&'static str], usize)> {
    let mut layouts = LAYOUTS.lock().unwrap();
    let got = layouts.entry(iface).or_insert_with(|| {
        let r = row()?;
        let at = galaxyvt::CLASSES.iter().position(|c| *c == iface.class())?;
        let index = galaxyvt::VERSIONS[r].1[at];
        if index < 0 {
            return None;
        }
        let names = iface.table()[index as usize];
        let base = MODULE.load(Ordering::Relaxed);
        match rtti_slots(base, iface.class()) {
            Some(n) if n == names.len() => Some(Layout { certain: n, names }),
            None => Some(Layout { certain: names.len(), names }),
            Some(n) => {
                if let Some(near) = nearby_layout(r, at, iface.table(), n) {
                    log!(
                        "galaxy {}: this DLL has {n} slots, the SDK's headers {}: a nearby SDK's {n}-slot layout fits",
                        iface.class(),
                        names.len()
                    );
                    return Some(Layout { certain: n, names: near });
                }
                // IUser's first methods (SignedIn, GetGalaxyID) are the same in every version.
                let certain = if iface == Iface::User { 3 } else { 0 };
                log!(
                    "galaxy {}: this DLL has {n} slots, the SDK's headers {}: {}",
                    iface.class(),
                    names.len(),
                    if certain > 0 { "only its first methods are answered" } else { "left alone" }
                );
                (certain > 0).then_some(Layout { certain, names })
            }
        }
    });
    got.as_ref().map(|l| (l.names, l.certain))
}

/// A DLL between two SDKs whose headers PeerParty has (1.152.10, between 1.152.9 and
/// 1.152.11) can have a class as the next one has it: the layout with the DLL's own slot
/// count from the same x.y series, newer versions first, then older.
fn nearby_layout(row: usize, at: usize, table: &'static [&'static [&'static str]], slots: usize) -> Option<&'static [&'static str]> {
    let (series, ..) = galaxyvt::VERSIONS[row];
    let same = |r: &usize| {
        let (v, ..) = galaxyvt::VERSIONS[*r];
        (v.0, v.1) == (series.0, series.1)
    };
    let newer = (row + 1..galaxyvt::VERSIONS.len()).take_while(same);
    let older = (0..row).rev().take_while(same);
    newer
        .chain(older)
        .map(|r| galaxyvt::VERSIONS[r].1[at])
        .filter(|i| *i >= 0)
        .map(|i| table[i as usize])
        .find(|names| names.len() == slots)
}

fn slot_of(iface: Iface, name: &str) -> Option<usize> {
    let (names, certain) = layout(iface)?;
    names.iter().position(|n| *n == name).filter(|i| *i < certain)
}

