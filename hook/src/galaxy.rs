fn on_event(ev: &Event) {
    match ev {
        Event::SearchDone { search, results } => search_done(*search, results),
        Event::JoinDone { lobby, result } => {
            let Some(id) = lobby_of(lobby) else { return };
            let listener = S.lock().unwrap().joins.remove(lobby).unwrap_or(0);
            // LOBBY_ENTER_RESULT_SUCCESS, DOES_NOT_EXIST, IS_FULL, ERROR.
            let code = match result {
                JoinResult::Ok => 0,
                JoinResult::NotFound => 1,
                JoinResult::Full => 2,
                _ => 3,
            };
            if code == 0 {
                if let Some(l) = lan().and_then(|lan| lan.lobby(lobby)) {
                    S.lock().unwrap().owners.insert(id, l.owner);
                }
            }
            log!("galaxy lobby {id} entered: {result:?}");
            let to = targets(LOBBY_ENTERED, listener);
            later(move || {
                for l in to {
                    virt!(l, 1, fn(*const u64, u32), &id, code);
                }
            });
        }
        Event::LobbyUpdated { lobby } => {
            let Some(id) = lobby_of(lobby) else { return };
            let owner = lan().and_then(|l| l.lobby(lobby)).map(|l| l.owner);
            let changed = owner.is_some_and(|o| S.lock().unwrap().owners.insert(id, o).is_some_and(|was| was != o));
            let data = targets(LOBBY_DATA, 0);
            let owners = if changed { targets(LOBBY_OWNER_CHANGE, 0) } else { Vec::new() };
            let new_owner = owner.map(galaxy_id).unwrap_or(0);
            later(move || {
                let none = 0u64;
                for l in data {
                    virt!(l, 1, fn(*const u64, *const u64), &id, &none);
                }
                for l in owners {
                    virt!(l, 1, fn(*const u64, *const u64), &id, &new_owner);
                }
            });
        }
        Event::MemberUpdated { lobby, member } => {
            let Some(id) = lobby_of(lobby) else { return };
            let who = galaxy_id(*member);
            let data = targets(LOBBY_DATA, 0);
            later(move || {
                for l in data {
                    virt!(l, 1, fn(*const u64, *const u64), &id, &who);
                }
            });
        }
        Event::MemberStatus { lobby, member, status } => {
            let Some(id) = lobby_of(lobby) else { return };
            let who = galaxy_id(*member);
            let me = lan().map(|l| l.me()) == Some(*member);
            if me && *status == MemberStatus::Closed {
                let to = targets(LOBBY_LEFT, 0);
                // LOBBY_LEAVE_REASON_LOBBY_CLOSED, or no I/O failure before 1.133.
                let reason = if sdk() >= (1, 133, 0) { 2 } else { 0 };
                later(move || {
                    for l in to {
                        virt!(l, 1, fn(*const u64, u32), &id, reason);
                    }
                });
                return;
            }
            let change = match status {
                MemberStatus::Joined => 0x1,
                MemberStatus::Left => 0x2,
                MemberStatus::Disconnected => 0x4,
                MemberStatus::Kicked => 0x8,
                _ => return,
            };
            if me {
                return;
            }
            let to = targets(LOBBY_MEMBER_STATE, 0);
            later(move || {
                for l in to {
                    virt!(l, 1, fn(*const u64, *const u64, u32), &id, &who, change);
                }
            });
        }
        Event::ChanRequest { peer, socket } if socket == P2P || socket == CHAT || socket == ext::IM => {
            // Galaxy has no sessions to accept.
            if let Some(lan) = lan() {
                lan.accept(*peer, socket);
            }
        }
        Event::PeerJoined(p) | Event::PresenceChanged(p) => {
            let id = galaxy_id(*p);
            let persona = targets(PERSONA_DATA_CHANGED, 0);
            let rich = if matches!(ev, Event::PresenceChanged(_)) { targets(RICH_PRESENCE, 0) } else { Vec::new() };
            later(move || {
                for l in persona {
                    virt!(l, 1, fn(Gid, u32), by_value(&id), PERSONA_CHANGE_NAME);
                }
                for l in rich {
                    virt!(l, 1, fn(Gid), by_value(&id));
                }
            });
        }
        Event::Invite { from, connect, lobby } if !connect.is_empty() => {
            let id = galaxy_id(*from);
            let decision = crate::invite::decision(*from, connect, lobby.as_ref());
            log!(
                "galaxy invite from {id} {}: connect={connect}",
                if decision.accept() { "accepted" } else { "passed to the game; waiting for the player" }
            );
            let to = targets(if decision.accept() { GAME_JOIN_REQUESTED } else { GAME_INVITATION_RECEIVED }, 0);
            let c = CString::new(connect.clone()).unwrap_or_default();
            later(move || {
                for l in to {
                    virt!(l, 1, fn(Gid, *const c_char), by_value(&id), c.as_ptr());
                }
            });
        }
        _ => {}
    }
}

fn search_done(search: u64, results: &[Lobby]) {
    let mut st = S.lock().unwrap();
    if let Some((id, listener)) = st.data_requests.remove(&search) {
        let found = results.iter().find(|l| lobby_of(&l.id) == Some(id)).cloned();
        if let Some(l) = &found {
            st.known.insert(id, l.clone());
        }
        let to = targets_locked(&st, LOBBY_DATA_RETRIEVE, listener);
        let data = if found.is_some() { targets_locked(&st, LOBBY_DATA, 0) } else { Vec::new() };
        st.queue.push_back(Box::new(move || {
            let none = 0u64;
            for l in to {
                if found.is_some() {
                    virt!(l, 1, fn(*const u64), &id);
                } else {
                    // FAILURE_REASON_LOBBY_DOES_NOT_EXIST
                    virt!(l, 2, fn(*const u64, u32), &id, 1);
                }
            }
            for l in data {
                virt!(l, 1, fn(*const u64, *const u64), &id, &none);
            }
        }));
        return;
    }
    let Some((s_id, listener, allow_full)) = st.search else { return };
    if s_id != search {
        return;
    }
    st.search = None;
    let mut hits: Vec<Lobby> = results
        .iter()
        .filter(|l| l.namespace == NS && lobby_of(&l.id).is_some())
        .filter(|l| allow_full || l.open_slots() > 0)
        .filter(|l| text(l, KEY_JOINABLE).is_none_or(|v| v != "0"))
        .filter(|l| st.filters.iter().all(|f| passes(l, f)))
        .cloned()
        .collect();
    for f in &st.filters {
        if let Filter::Near(k, target) = f {
            hits.sort_by_key(|l| text(l, k).and_then(|t| t.trim().parse::<i64>().ok()).map_or(i64::MAX, |v| (v - target).abs()));
        }
    }
    hits.truncate(st.count.unwrap_or(100));
    st.results = hits.iter().filter_map(|l| lobby_of(&l.id)).collect();
    for l in hits {
        if let Some(id) = lobby_of(&l.id) {
            st.known.insert(id, l);
        }
    }
    st.filters.clear();
    st.count = None;
    let n = st.results.len() as u32;
    log!("galaxy lobby list: {n} lobbies");
    let to = targets_locked(&st, LOBBY_LIST, listener);
    st.queue.push_back(Box::new(move || {
        for l in to {
            // LOBBY_LIST_RESULT_SUCCESS
            virt!(l, 1, fn(u32, u32), n, 0);
        }
    }));
}

fn targets_locked(st: &State, kind: &str, specific: usize) -> Vec<usize> {
    let mut v = Vec::new();
    if specific != 0 {
        v.push(specific);
    }
    let globals = listener_type(kind).and_then(|k| st.listeners.get(&k));
    for l in globals.into_iter().flatten() {
        if !v.contains(l) {
            v.push(*l);
        }
    }
    v
}

/// Runs from the game's ProcessData: LAN events, lobby messages and packets become
/// listener calls, made here on the game's thread.
fn pump() {
    if lan().is_none() {
        return;
    }
    for ev in net::take(Front::Galaxy) {
        on_event(&ev);
    }
    if let Some(lan) = lan() {
        while let Some(p) = lan.receive_where(None, |s| s == CHAT) {
            if p.data.len() >= 8 {
                let lobby = u64::from_le_bytes(p.data[..8].try_into().unwrap());
                received_message(lobby, galaxy_id(p.peer), p.data[8..].to_vec());
            }
        }
    }
    ext::pump();
    let fresh = take_packets();
    if !fresh.is_empty() {
        let to = targets(NETWORKING, 0);
        later(move || {
            for (channel, size) in fresh {
                for l in &to {
                    virt!(*l, 1, fn(u32, u8), size, channel);
                }
            }
        });
    }
    loop {
        let next = S.lock().unwrap().queue.pop_front();
        let Some(f) = next else { break };
        f();
    }
}

