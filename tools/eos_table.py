"""Generates hook/src/eos/table.rs from the EOS SDK C headers.

    python tools/eos_table.py <dir with eos_*.h> > hook/src/eos/table.rs

Every exported EOS function gets a class saying what the LAN layer does with it when it
doesn't implement the function itself:

- pass: the real SDK answers (platform, logging, string helpers). These never see a
  peerparty-minted handle.
- async: completes on the next tick with EOS_NoConnection. The callback info starts
  with ResultCode and ClientData; the generator checks that.
- add_notify: hands out a notification id and never fires.
- copy: returns EOS_NotFound and nulls the out pointer.
- zero: returns 0 (counts, handles, booleans, enums).
- result: returns EOS_NoConnection.
- void: does nothing.

`slots` is the argument size in 4-byte stack slots, which an x86 stdcall callee pops.
Only names and classes are emitted; nothing from the headers' text.
"""

import re
import sys
from pathlib import Path

# Families the real SDK keeps answering. Anything that could receive a ProductUserId,
# EpicAccountId or lobby/session handle minted by peerparty is not in here.
PASS_PREFIXES = (
    "EOS_Initialize",
    "EOS_Shutdown",
    "EOS_GetVersion",
    "EOS_EResult_",
    "EOS_ByteArray_",
    "EOS_Logging_",
    "EOS_Platform_",
    "EOS_IntegratedPlatform_CreateIntegratedPlatformOptionsContainer",
    "EOS_IntegratedPlatformOptionsContainer_",
    "EOS_ContinuanceToken_",
)

U64_TYPES = {"uint64_t", "int64_t", "double", "EOS_NotificationId", "EOS_UI_EventId"}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse(headers):
    funcs, callbacks, structs, u64 = {}, {}, {}, set(U64_TYPES)
    for path in sorted(Path(headers).glob("eos_*.h")):
        text = strip_comments(path.read_text(encoding="utf-8", errors="replace"))
        for m in re.finditer(r"typedef\s+(?:u?int64_t|double)\s+(\w+)\s*;", text):
            u64.add(m.group(1))
        for m in re.finditer(r"EOS_DECLARE_FUNC\(([^)]*)\)\s+(EOS_\w+)\s*\((.*?)\)\s*;", text, re.S):
            params = [p.strip() for p in m.group(3).split(",") if p.strip() and p.strip() != "void"]
            funcs[m.group(2)] = (m.group(1).strip(), params)
        for m in re.finditer(r"EOS_DECLARE_CALLBACK\(\s*(\w+)\s*,(.*?)\)\s*;", text, re.S):
            callbacks[m.group(1)] = m.group(2).strip()
        for m in re.finditer(r"EOS_DECLARE_CALLBACK_RETVALUE\([^,]+,\s*(\w+)\s*,(.*?)\)\s*;", text, re.S):
            callbacks[m.group(1)] = m.group(2).strip()
        for m in re.finditer(r"EOS_STRUCT\((\w+),\s*\((.*?)\)\);", text, re.S):
            fields = [f.strip() for f in m.group(2).split(";") if f.strip()]
            structs[m.group(1)] = [f.split()[-1].strip("*") for f in fields]
    return funcs, callbacks, structs, u64


def ptype(param):
    """Parameter type without its name."""
    parts = param.replace("*", " * ").split()
    return " ".join(parts[:-1]) if len(parts) > 1 else parts[0]


def slots(params, u64):
    n = 0
    for p in params:
        t = ptype(p)
        base = t.replace("const", "").replace("*", "").strip()
        n += 2 if ("*" not in t and base in u64) else 1
    return n


def bare(t):
    return t.replace("const", "").replace("*", "").strip()


def is_out_handle(param):
    """An out parameter the SDK fills with a pointer or handle: `EOS_Foo** OutFoo` or
    `EOS_HFoo* OutHandle`. Out buffers (`char* OutBuffer`) are not."""
    name = param.replace("*", " ").split()[-1]
    t = ptype(param)
    return name.startswith("Out") and (t.count("*") >= 2 or (t.count("*") == 1 and bare(t).startswith("EOS_H")))


def classify(name, ret, params, callbacks, structs):
    if name.startswith(PASS_PREFIXES):
        return "pass"
    types = [ptype(p) for p in params]
    callback_params = [t for t in types if bare(t) in callbacks]
    if ret == "void" and len(params) == 4 and len(callback_params) == 1 and bare(types[3]) in callbacks:
        info_arg = callbacks[bare(types[3])]
        info = re.sub(r"const|\*", " ", info_arg).split()[0]
        fields = structs.get(info, [])
        if fields[:2] == ["ResultCode", "ClientData"]:
            return "async"
        return "void"  # a notification-style callback taken by a void call
    if "_AddNotify" in name and ret == "EOS_NotificationId":
        return "add_notify"
    if ret == "EOS_EResult":
        outs = [i for i, p in enumerate(params) if i > 0 and is_out_handle(p)]
        if outs:
            return "copy%d" % outs[0]
        return "result"
    if ret == "void":
        return "void"
    return "zero"


def main():
    funcs, callbacks, structs, u64 = parse(sys.argv[1])
    print("// Generated by tools/eos_table.py from the EOS SDK headers. Do not edit.")
    print("// (name, class, x86 stack slots). See tools/eos_table.py for the classes.")
    print()
    print("use super::fail::Class::{self, *};")
    print()
    print("pub static TABLE: &[(&str, Class, u8)] = &[")
    for name in sorted(funcs):
        ret, params = funcs[name]
        cls = classify(name, ret, params, callbacks, structs)
        variant = {
            "pass": "Pass",
            "async": "Async",
            "add_notify": "AddNotify",
            "result": "Result",
            "void": "Void",
            "zero": "Zero",
        }.get(cls)
        if variant is None:
            variant = "Copy(%s)" % cls[4:]
        print('    ("%s", %s, %d),' % (name, variant, slots(params, u64)))
    print("];")


if __name__ == "__main__":
    main()
