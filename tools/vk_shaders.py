"""Compiles the Vulkan overlay's own shaders (hook/src/video/glsl) into SPIR-V words in
hook/src/video/vkshaders.rs, between its "generated" markers.

    python tools/vk_shaders.py

Needs naga (MIT or Apache-2.0; `cargo install naga-cli`) on PATH. The build doesn't: the
words are checked in, and this is only run when a shader changes. SPIR-V 1.0, so a
Vulkan 1.0 device takes them; clip space as written (no Y flip).
"""

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GLSL = ROOT / "hook" / "src" / "video" / "glsl"
TARGET = ROOT / "hook" / "src" / "video" / "vkshaders.rs"
BEGIN = "// --- generated by tools/vk_shaders.py: don't edit by hand ---"
END = "// --- end of generated ---"

# (const name, source file, what it is)
SHADERS = [
    ("HDR_VERT", "overlay_hdr.vert", "the quad, for the HDR fragment shaders"),
    ("SCRGB_FRAG", "overlay_scrgb.frag", "the frame into an scRGB swap chain"),
    ("PQ_FRAG", "overlay_pq.frag", "the frame into an HDR10 (PQ) swap chain"),
]

# No console window flashes up for naga.
NO_WINDOW = 0x08000000 if sys.platform == "win32" else 0


def naga(*args):
    return subprocess.run(["naga", *args], capture_output=True, text=True, creationflags=NO_WINDOW)


def compile_words(source: Path, out_dir: Path) -> list[int]:
    out = out_dir / (source.name + ".spv")
    r = naga("--input-kind", "glsl", "--shader-stage", source.suffix[1:], "--spirv-version", "1.0", "--keep-coordinate-space", str(source), str(out))
    if r.returncode != 0 or not out.exists():
        sys.exit(f"naga failed on {source.name}:\n{r.stdout}{r.stderr}")
    data = out.read_bytes()
    assert len(data) % 4 == 0
    return [int.from_bytes(data[i : i + 4], "little") for i in range(0, len(data), 4)]


def rust_array(name: str, words: list[int], what: str, source: str) -> str:
    lines = [f"/// {what[0].upper()}{what[1:]} (glsl/{source}).", f"pub const {name}: [u32; {len(words)}] = ["]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i : i + 8]) + ",")
    lines.append("];")
    return "\n".join(lines)


def main():
    version = naga("--version")
    if version.returncode != 0:
        sys.exit("naga isn't on PATH: cargo install naga-cli")
    with tempfile.TemporaryDirectory() as tmp:
        blocks = [rust_array(name, compile_words(GLSL / src, Path(tmp)), what, src) for name, src, what in SHADERS]
    text = TARGET.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END)
    generated = f"{BEGIN}\n// {version.stdout.strip()}\n\n" + "\n\n".join(blocks) + "\n"
    TARGET.write_text(text[:start] + generated + text[end:], encoding="utf-8", newline="\n")
    print(f"{TARGET.relative_to(ROOT)}: {', '.join(n for n, _, _ in SHADERS)}")


if __name__ == "__main__":
    main()
